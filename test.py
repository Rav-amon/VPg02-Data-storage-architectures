def get_embedding(text: str) -> list[float]:
    """Считает вектор эмбеддинга для одной фразы.

    Входные значения:
        text: текст фразы.

    Выходные значения:
        list[float]: вектор модели text-embedding-3-small.
    """
    response = client.embeddings.create(
        input=text,
        model="text-embedding-3-small",
    )
    return response.data[0].embedding

